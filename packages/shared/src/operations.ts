/** 操作目录：HTTP API / CLI / Agent Tool 的单一定义来源。
 *  新增一个接口 = 这里加一条，CLI 与工具立刻可用，不需要三份手写。 */

export type OperationMethod = "GET" | "POST" | "PATCH" | "PUT" | "DELETE";

export type OperationParamIn = "path" | "query" | "body" | "file";

export type OperationParamType = "string" | "number" | "boolean" | "json";

/** 风险级别：read 只读；write 会改数据；destructive 不可逆（CLI 需 --yes） */
export type OperationRisk = "read" | "write" | "destructive";

export interface OperationParam {
  /** 参数名（camelCase），CLI 自动转成 --kebab-case */
  name: string;
  in: OperationParamIn;
  type: OperationParamType;
  required?: boolean;
  desc?: string;
  /** CLI 缺省值（不写则不带该字段） */
  default?: string | boolean | number;
  /** 仅用于帮助输出 */
  values?: string[];
  /** in:"file" 时：把文件文本内容写入该 body 字段（不按 multipart 上传）；缺省直接上传文件 */
  target?: string;
  /** in:"file" 时文件大小上限（字节）；上传缺省 50MB，target 读文本缺省 4MB */
  maxBytes?: number;
}

export interface OperationDef {
  /** 唯一键，CLI 命令即 `aiwb <key>`，如 mail.messages.list */
  key: string;
  module: string;
  action: string;
  summary: string;
  method: OperationMethod;
  /** 相对 /api 的路径，路径参数写 :name */
  path: string;
  permission?: string;
  risk: OperationRisk;
  params?: OperationParam[];
}

